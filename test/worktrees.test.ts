// Linked worktree isolation and explicit Git metadata exclusion. These need
// live Git administrative links and before/after filesystem assertions, which
// cannot be committed as portable conformance fixtures. docs/CONFIG.MD.

import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { test } from "node:test";

const cli = fileURLToPath(new URL("../src/cli.js", import.meta.url));
const config = "pin: 0.9.0\nroot: espalier\nignoreFiles: []\nskip: []\n";
const rule = 'export const description = "source"; export const rule = "Source."; export function lint() {}\n';

function write(root: string, at: string, text: string): void {
  mkdirSync(path.dirname(path.join(root, at)), { recursive: true });
  writeFileSync(path.join(root, at), text);
}

function repository(root: string): void {
  write(root, "espalier.config.yaml", config);
  write(root, ".espalierignore", ".git\n");
  write(root, "espalier/main.ts.mjs", rule);
  write(root, "main.ts", "export {};\n");
}

function run(root: string, ...args: string[]) {
  const result = spawnSync(process.execPath, [cli, ...args], { cwd: root, encoding: "utf8" });
  assert.ifError(result.error);
  return result;
}

function git(root: string, ...args: string[]): void {
  const result = spawnSync("git", ["-c", "user.name=Test", "-c", "user.email=test@example.invalid",
    "-c", "commit.gpgsign=false", ...args], { cwd: root, encoding: "utf8" });
  assert.ifError(result.error);
  assert.equal(result.status, 0, result.stderr);
}

test("linked worktrees leave parent lint, guidance and migration unchanged", () => {
  const root = mkdtempSync(path.join(os.tmpdir(), "espalier-worktree-"));
  try {
    repository(root);
    git(root, "init", "-b", "main");
    assert.equal(run(root, "build").status, 0);
    const baseline = readFileSync(path.join(root, "AGENTS.MD"), "utf8");
    git(root, "add", ".");
    git(root, "commit", "-m", "baseline");
    const at = ".claude/worktrees/probe";
    git(root, "worktree", "add", "--detach", at, "main");
    const worktree = path.join(root, at);

    for (const cwd of [root, worktree]) {
      const lint = run(cwd, "lint", "--format", "jsonl");
      assert.equal(lint.status, 0, lint.stdout);
      assert.equal(lint.stdout, "");
      const checked = run(cwd, "build", "--check");
      assert.equal(checked.status, 0, checked.stdout);
      assert.equal(checked.stdout, "Generated guidance is up to date (1 file).\n");
    }

    // Relative gitfile targets and symlink spellings identify the same checkout.
    const marker = readFileSync(path.join(worktree, ".git"), "utf8").trim().slice("gitdir: ".length);
    write(worktree, ".git", `gitdir: ${path.relative(worktree, marker)}\n`);
    symlinkSync(at, path.join(root, "worktree-alias"), "dir");
    assert.equal(run(root, "build", "--check").status, 0);
    repository(path.join(worktree, "packages/inside"));
    assert.equal(run(worktree, "build").status, 0);
    assert.match(readFileSync(path.join(worktree, "packages/inside/AGENTS.MD"), "utf8"), /## Governance boundary/);
    assert.doesNotMatch(readFileSync(path.join(worktree, "AGENTS.MD"), "utf8"), /## Governance boundary/);

    // The parent must not load child ignores, execute child rules, or sweep its files.
    write(worktree, ".espalierignore", "main.ts\n");
    write(worktree, "espalier.config.yaml", config.replace("0.9.0", "0.4.0"));
    write(worktree, "orphan/AGENTS.MD", "<!-- generated by espalier -->\nkeep me\n");
    write(worktree, "stray.txt", "unowned\n");
    assert.equal(run(root, "lint").status, 0);
    assert.equal(run(root, "build").status, 0);
    assert.equal(readFileSync(path.join(root, "AGENTS.MD"), "utf8"), baseline);
    assert.equal(readFileSync(path.join(worktree, "orphan/AGENTS.MD"), "utf8"), "<!-- generated by espalier -->\nkeep me\n");
    assert.equal(run(root, "migrate").status, 0);
    assert.equal(readFileSync(path.join(worktree, "espalier.config.yaml"), "utf8"), config.replace("0.9.0", "0.4.0"));
    const explained = run(root, "explain", `${at}/main.ts`, "--format", "jsonl");
    assert.equal(explained.status, 1);
    assert.equal(JSON.parse(explained.stdout).ignoredBy, "worktree");

    // Without its own config, discovery must not escape into the enclosing repo.
    rmSync(path.join(worktree, "espalier.config.yaml"));
    mkdirSync(path.join(worktree, "deep/nested"), { recursive: true });
    const absent = run(path.join(worktree, "deep/nested"), "lint", "--format", "jsonl");
    assert.equal(absent.status, 2);
    assert.equal(JSON.parse(absent.stdout).code, "config_not_found");
    assert.equal(run(worktree, "lint", "--config", path.join(root, "espalier.config.yaml")).status, 0);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("authored paths cannot require or generate files inside a linked worktree", () => {
  const root = mkdtempSync(path.join(os.tmpdir(), "espalier-worktree-declared-"));
  try {
    repository(root);
    git(root, "init", "-b", "main");
    assert.equal(run(root, "build").status, 0);
    git(root, "add", ".");
    git(root, "commit", "-m", "baseline");
    git(root, "worktree", "add", "--detach", "copies/probe", "main");
    const worktree = path.join(root, "copies/probe");
    const before = readFileSync(path.join(worktree, "AGENTS.MD"), "utf8");
    // The outer architecture must not claim authority over this checkout.
    write(root, "espalier/copies/probe/absent.ts.mjs", rule);
    write(root, "espalier/copies/probe/[member].ts.mjs", `${rule}\nexport const minMatches = 1;\n`);
    const lint = run(root, "lint", "--format", "jsonl");
    assert.equal(lint.status, 0, lint.stdout);
    assert.equal(run(root, "build").status, 0);
    assert.equal(readFileSync(path.join(worktree, "AGENTS.MD"), "utf8"), before);
    assert.equal(run(root, "build", "--check").status, 0);
    const create = run(root, "create", "copies/probe/absent.ts");
    assert.notEqual(create.status, 0);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("ordinary child projects and submodules remain governed", () => {
  const scratch = mkdtempSync(path.join(os.tmpdir(), "espalier-submodule-"));
  const root = path.join(scratch, "parent");
  const source = path.join(scratch, "source");
  try {
    repository(root);
    repository(source);
    repository(path.join(root, "packages/plain"));
    repository(path.join(root, "packages/separate"));
    git(root, "init", "-b", "main");
    git(path.join(root, "packages/plain"), "init", "-b", "main");
    git(path.join(root, "packages/separate"), "init", "-b", "main", "--separate-git-dir", path.join(scratch, "separate.git"));
    git(source, "init", "-b", "main");
    git(source, "add", ".");
    git(source, "commit", "-m", "submodule");
    git(root, "-c", "protocol.file.allow=always", "submodule", "add", source, "packages/sub");
    write(root, ".espalierignore", ".git\n.gitmodules\n");
    assert.equal(run(root, "lint").status, 0);
    assert.equal(run(root, "build").status, 0);
    const document = readFileSync(path.join(root, "AGENTS.MD"), "utf8");
    assert.match(document, /`packages\/plain\/`/);
    assert.match(document, /`packages\/sub\/`/);
    assert.match(document, /`packages\/separate\/`/);
    for (const child of ["plain", "sub", "separate"]) {
      assert.match(readFileSync(path.join(root, "packages", child, "AGENTS.MD"), "utf8"), /## Governance boundary/);
    }
    assert.equal(run(root, "build", "--check").stdout, "Generated guidance is up to date (4 files).\n");
    write(root, "packages/sub/main.ts", "bad\n");
    write(root, "packages/sub/espalier/main.ts.mjs", rule.replace("lint() {}", 'lint({emit}) { emit({code:"child-check", message:"visited"}); }'));
    const lint = run(root, "lint", "--format", "jsonl");
    assert.equal(lint.status, 1);
    assert.equal(JSON.parse(lint.stdout).espalier, "packages/sub");
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
});

test("Git metadata files, directories and broken symlinks are excluded by an explicit bare-name pattern", () => {
  const root = mkdtempSync(path.join(os.tmpdir(), "espalier-git-metadata-"));
  try {
    repository(root);
    write(root, ".git/objects/probe", "metadata\n");
    write(root, "nested/.git", "gitdir: missing\n");
    mkdirSync(path.join(root, "linked"));
    symlinkSync("missing", path.join(root, "linked/.git"));
    write(root, ".espalierignore", "# Version control metadata.\n.git\n");
    const lint = run(root, "lint", "--format", "jsonl");
    assert.equal(lint.status, 0, lint.stdout);
    assert.equal(lint.stdout, "");
    assert.equal(run(root, "build").status, 0);
    assert.match(readFileSync(path.join(root, "AGENTS.MD"), "utf8"), /Version control metadata/);
    for (const at of [".git/", ".git/objects/probe", "nested/.git", "linked/.git"]) {
      const explained = run(root, "explain", at, "--format", "jsonl");
      assert.equal(explained.status, 1);
      assert.equal(JSON.parse(explained.stdout).ignoredBy, ".espalierignore");
    }
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("Git metadata can be governed when the explicit exclusion is removed", () => {
  const root = mkdtempSync(path.join(os.tmpdir(), "espalier-git-governed-"));
  try {
    repository(root);
    write(root, ".espalierignore", "");
    write(root, ".git/metadata.txt", "metadata\n");
    write(root, "nested/.git", "gitdir: missing\n");
    write(root, "espalier/.git/metadata.txt.mjs", rule);
    write(root, "espalier/nested/.git.mjs", rule);
    const lint = run(root, "lint", "--format", "jsonl");
    assert.equal(lint.status, 0, lint.stdout);
    for (const at of [".git/metadata.txt", "nested/.git"]) {
      const explained = run(root, "explain", at, "--format", "jsonl");
      assert.equal(explained.status, 0, explained.stdout);
      assert.equal(JSON.parse(explained.stdout).rule, `${at}.mjs`);
    }
    write(root, ".espalierignore", ".git\n");
    const excluded = run(root, "lint", "--format", "jsonl");
    assert.equal(excluded.status, 2, excluded.stdout);
    assert.match(excluded.stdout, /ignored_required_path/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

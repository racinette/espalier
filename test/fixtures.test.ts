interface Expected {
  exit?: number;
  error?: string | Record<string, unknown>;
  issues?: unknown[];
  /** Extra arguments for the lint run — scoping is the case that needs them. */
  args?: string[];
  /**
   * Warnings the lint run must emit, in order. The partial-run line is the only
   * place a child espalier that was visited and found nothing differs from one
   * that was never visited, so a fixture about scoping has to assert it.
   */
  warnings?: string[];
  explain?: Record<string, { exit: number; object: unknown; human?: string }>;
  ownership?: Record<string, string | null>;
  stderr?: string[];
  /** A file holding the exact `--format human` stdout of the same lint run. */
  human?: string;
  /** Environment the lint run is given, on top of the harness's own. */
  env?: Record<string, string>;
  again?: Rerun;
  build?: WriteRun;
  init?: WriteRun;
  adopt?: WriteRun;
}

/** A command that writes: `build` and `init` are asserted the same way. */
interface WriteRun {
  exit: number;
  args?: string[];
  report?: unknown[];
  /**
   * Warning messages the run must emit, in order. A warning is advice about
   * what was written rather than part of the record of it, so it is compared
   * separately from `report`.
   */
  warnings?: string[];
  /** A file holding the exact `--format human` stdout of the same run. */
  human?: string;
}

/**
 * A second `lint` over the same copy, after the tree or the environment
 * changed. Only an incremental run has anything to say here: everything else
 * espalier does is settled by the first run, and a fixture that reran without
 * a cache would assert that the same input gives the same answer.
 */
interface Rerun {
  /** A directory copied over the copy: files to add, or to replace. */
  apply?: string;
  /** Paths removed from the copy. */
  delete?: string[];
  /** Environment for this run only. */
  env?: Record<string, string>;
  exit: number;
  issues?: unknown[];
}

/** Scaffolding for the harness, never part of the repository under test. */
const SCAFFOLDING = new Set([
  "FIXTURE.MD",
  "expected.json",
  "expected-build",
  "expected-init",
  "expected-adopt",
  "human",
  "after",
]);

const PROVENANCE = "<!-- generated by espalier";

/**
 * Compares `actual` against `expected`, ignoring anything `expected` does not
 * mention. The rule applies at every depth, so an expected `metadata` naming
 * two keys asserts nothing about a third. Arrays are compared in order and by
 * length — a declared list is sorted, so its order is meaningful.
 *
 * Returns a description of the first mismatch, or null when it matches.
 */
function mismatch(actual: unknown, expected: unknown, at: string): string | null {
  if (Array.isArray(expected)) {
    if (!Array.isArray(actual)) {
      return `${at}: expected an array, got ${JSON.stringify(actual)}`;
    }
    if (actual.length !== expected.length) {
      return `${at}: expected ${expected.length} entries, got ${actual.length}`;
    }
    for (const [i, value] of expected.entries()) {
      const found = mismatch(actual[i], value, `${at}[${i}]`);
      if (found) return found;
    }
    return null;
  }

  if (expected !== null && typeof expected === "object") {
    if (actual === null || typeof actual !== "object" || Array.isArray(actual)) {
      return `${at}: expected an object, got ${JSON.stringify(actual)}`;
    }
    const target = actual as Record<string, unknown>;
    for (const [key, value] of Object.entries(expected)) {
      if (!(key in target)) return `${at}.${key}: absent`;
      const found = mismatch(target[key], value, `${at}.${key}`);
      if (found) return found;
    }
    return null;
  }

  if (actual !== expected) {
    return `${at}: expected ${JSON.stringify(expected)}, got ${JSON.stringify(actual)}`;
  }
  return null;
}

/** Every file under `dir`, repository-relative and sorted. */
function walk(dir: string, prefix = ""): string[] {
  const found: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    const at = prefix === "" ? entry.name : `${prefix}/${entry.name}`;
    if (entry.isDirectory()) found.push(...walk(path.join(dir, entry.name), at));
    else found.push(at);
  }
  return found;
}

/**
 * Every path under `dir` as the tool would see it: links followed, a link onto
 * a directory containing it refused. Separate from `walk` above, which compares
 * generated trees and has no links to meet — this one is the independent list
 * the agreement sweep asks about, so it must not be built from the thing it is
 * checking.
 */
function walkFollowing(dir: string, prefix = "", ancestors?: Set<string>): string[] {
  const stats = statSync(dir);
  const seen = ancestors ?? new Set<string>([`${stats.dev}:${stats.ino}`]);
  const found: string[] = [];

  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    const at = prefix === "" ? entry.name : `${prefix}/${entry.name}`;
    const absolute = path.join(dir, entry.name);
    let resolved;
    try {
      resolved = statSync(absolute);
    } catch {
      // A link pointing nowhere. The run it is about fails, and a fixture
      // asserting a failure is not swept.
      continue;
    }
    if (!resolved.isDirectory()) {
      if (resolved.isFile()) found.push(at);
      continue;
    }
    const id = `${resolved.dev}:${resolved.ino}`;
    if (seen.has(id)) continue;
    seen.add(id);
    found.push(...walkFollowing(absolute, at, seen));
    seen.delete(id);
  }
  return found;
}

/**
 * Issues are compared as an unordered multiset: the runner promises no order,
 * but two identical issues are not one issue. Matching is greedy, which is
 * sufficient while no fixture expects two issues where one expectation is a
 * strict refinement of another.
 */
function compareIssues(actual: unknown[], expected: unknown[]): string[] {
  const unmatched = [...actual];
  const problems: string[] = [];

  for (const [i, want] of expected.entries()) {
    const at = unmatched.findIndex((got) => mismatch(got, want, "issue") === null);
    if (at === -1) {
      problems.push(`no issue matched expected[${i}]: ${JSON.stringify(want)}`);
    } else {
      unmatched.splice(at, 1);
    }
  }

  for (const extra of unmatched) {
    problems.push(`unexpected issue: ${JSON.stringify(extra)}`);
  }
  return problems;
}

function run(cwd: string, args: string[], env?: Record<string, string>) {
  const result = spawnSync(process.execPath, [cli, ...args], {
    cwd,
    encoding: "utf8",
    env: env === undefined ? process.env : { ...process.env, ...env },
  });
  if (result.error) throw result.error;
  return {
    status: result.status ?? -1,
    stdout: result.stdout,
    stderr: result.stderr,
  };
}

function parseLines(stdout: string, what: string): Record<string, unknown>[] {
  return stdout
    .split("\n")
    .filter((line) => line.trim() !== "")
    .map((line, i) => {
      try {
        return JSON.parse(line) as Record<string, unknown>;
      } catch {
        throw new Error(`${what}: line ${i + 1} is not JSON: ${line}`);
      }
    });
}

